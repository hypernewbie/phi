#!/usr/bin/env node
// Bundle the Phi↔Pi extension factory into one self-contained CJS file
// the Pi host loads with --extension. All dependencies are bundled;
// only Node.js builtins stay external. Output is deterministic and
// committed: bonus/pi-phi/dist/pi-phi-extension.cjs plus dist/NOTICES.txt.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { builtinModules } from 'node:module';
import {
    existsSync,
    mkdirSync,
    readFileSync,
    readdirSync,
    writeFileSync,
} from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(new URL('..', import.meta.url).pathname);
const pkgDir = join(root, 'bonus/pi-phi');
const distDir = join(pkgDir, 'dist');
const metaPath = join(distDir, 'meta.json');

mkdirSync(distDir, { recursive: true });

const esbuildBin = join(
    pkgDir,
    'node_modules',
    '.bin',
    process.platform === 'win32' ? 'esbuild.exe' : 'esbuild',
);
if (!existsSync(esbuildBin)) {
    console.error(
        'esbuild not found: run pnpm install first (pinned devDependency)',
    );
    process.exit(1);
}

execFileSync(
    esbuildBin,
    [
        join('src', 'extension-entry.cts'),
        '--bundle',
        '--platform=node',
        '--target=node20',
        '--format=cjs',
        `--outfile=${join('dist', 'pi-phi-extension.cjs')}`,
        `--metafile=${join('dist', 'meta.json')}`,
        '--log-level=warning',
    ],
    { cwd: pkgDir, stdio: 'inherit' },
);

// Every bundle import must be a Node.js builtin: the artifact loads
// from directories without node_modules (verified by the host checks).
const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
const builtins = new Set([
    ...builtinModules,
    ...builtinModules.map((name) => `node:${name}`),
]);
for (const [output, info] of Object.entries(meta.outputs)) {
    for (const entry of info.imports ?? []) {
        if (!builtins.has(entry.path)) {
            console.error(`non-builtin external in ${output}: ${entry.path}`);
            process.exit(1);
        }
    }
}

// Notices for every bundled third-party package.
const packages = new Map();
for (const input of Object.keys(meta.inputs)) {
    const marker = 'node_modules/';
    const idx = input.lastIndexOf(marker);
    if (idx < 0) continue;
    const rest = input.slice(idx + marker.length);
    const parts = rest.split('/');
    const name = rest.startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
    if (!name || name === '.bin') continue;
    const dir = join(pkgDir, input.slice(0, idx + marker.length), name);
    if (!packages.has(name) && existsSync(join(dir, 'package.json'))) {
        packages.set(name, dir);
    }
}
const sections = [];
const collected = new Map();
for (const [name, dir] of [...packages.entries()].sort()) {
    const manifest = JSON.parse(
        readFileSync(join(dir, 'package.json'), 'utf8'),
    );
    let license = '';
    for (const file of readdirSync(dir)) {
        if (/^license(\.|$)|^licence(\.|$)|^copying/i.test(file)) {
            license = readFileSync(join(dir, file), 'utf8').trim();
            break;
        }
    }
    collected.set(name, {
        version: manifest.version,
        expression: manifest.license ?? 'see text',
        license,
    });
}
// Some packages declare SPDX IDs without shipping a license file. Fill
// those from identical canonical texts already collected in this same
// bundle; fail loudly when no identical text exists.
const knownTexts = new Map();
for (const entry of collected.values()) {
    if (entry.license !== '' && /^[A-Za-z0-9.+-]+$/.test(entry.expression)) {
        knownTexts.set(entry.expression, entry.license);
    }
}
for (const [name, entry] of collected) {
    if (entry.license === '') {
        const ids = entry.expression.split(/[^A-Za-z0-9.+-]+/).filter(Boolean);
        const texts = [];
        for (const id of ids) {
            if (id === 'AND' || id === 'OR' || id === 'WITH') continue;
            const text = knownTexts.get(id);
            if (text === undefined) {
                console.error(
                    `no license text for ${name}@${entry.version} (${entry.expression})`,
                );
                process.exit(1);
            }
            if (!texts.includes(text)) texts.push(text);
        }
        if (texts.length === 0) {
            console.error(
                `no license text for ${name}@${entry.version} (${entry.expression})`,
            );
            process.exit(1);
        }
        entry.license = texts.join('\n\n');
    }
    sections.push(
        `== ${name}@${entry.version} (${entry.expression}) ==\n\n${entry.license}\n`,
    );
}
writeFileSync(
    join(distDir, 'NOTICES.txt'),
    `Phi Pi integration runtime: third-party notices.\nGenerated by scripts/pi-phi-build.mjs; do not edit.\n\n${sections.join('\n')}`,
);

const bytes = readFileSync(join(distDir, 'pi-phi-extension.cjs')).length;
console.log(
    `pi-phi runtime bundled: dist/pi-phi-extension.cjs (${bytes} bytes), ${packages.size} packages noticed`,
);

// VERSION pins the bundle for phi's stable-path gating: the Go side
// embeds this file next to the bundle and rewrites the stable copy
// when the stamp differs. The stamp carries the package version AND
// the bundle hash, so a bundle change refreshes the stable copy even
// when the version number does not move. Single source is the package
// version; a missing or unparsable version fails the build.
let pkgVersion;
try {
    pkgVersion = JSON.parse(
        readFileSync(join(pkgDir, 'package.json'), 'utf8'),
    ).version;
} catch (err) {
    console.error(`cannot parse pi-phi package.json: ${err}`);
    process.exit(1);
}
if (typeof pkgVersion !== 'string' || !/^\d+\.\d+\.\d+/.test(pkgVersion)) {
    console.error(`unparsable pi-phi package version: ${pkgVersion}`);
    process.exit(1);
}
const bundleHash = createHash('sha256')
    .update(readFileSync(join(distDir, 'pi-phi-extension.cjs')))
    .digest('hex');
writeFileSync(join(distDir, 'VERSION'), `${pkgVersion} ${bundleHash}\n`);
console.log(
    `pi-phi version stamped: dist/VERSION (${pkgVersion} ${bundleHash.slice(0, 12)})`,
);
