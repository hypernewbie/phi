import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const iconDir = join(root, 'web/vendor/model-icons');
const outFile = join(root, 'web-src/model-icon-data.ts');

const files = readdirSync(iconDir)
    .filter((file) => file.endsWith('.svg'))
    .sort();
const entries = files.map((file) => {
    const id = file.slice(0, -'.svg'.length);
    const svg = readFileSync(join(iconDir, file), 'utf8');
    const url = `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
    return `    ${JSON.stringify(id)}: ${JSON.stringify(url)},`;
});

const output = `/* Generated by scripts/build-model-icons.mjs. Do not edit. */

// Data URLs keep compact marks synchronous and theme-colorable: no second
// request, no Image decode, and no robot frame while a known mark loads.
export const PROVIDER_MARK_URLS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;

writeFileSync(outFile, output);
console.log(`wrote ${files.length} marks to ${outFile}`);
